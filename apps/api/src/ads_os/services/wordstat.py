"""Бриф → маски для Вордстата.

Собрать запросы за специалиста нельзя. Вордстат отдаёт данные только вошедшему
человеку, требует подтверждения, что он человек, и прямо запрещает
автоматический сбор. Обещать здесь автоматику — значит обещать то, что либо не
заработает, либо закончится блокировкой аккаунта клиента.

Зато можно снять с человека всё остальное. Долгая часть сбора — не нажатия в
Вордстате, а придумывание, что вообще туда вводить: какие слова описывают
услугу, какие синонимы люди используют вместо ваших, что сразу отсечь минусами.
Это выводится из короткого брифа, и здесь оно и выводится.

Дальше человек делает четыре нажатия в Вордстате и возвращается с выгрузкой —
а разбор, чистка и группировка снова наши.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .morphology import fold_beglye, stem, tokenize

#: Сколько исходных слов берём в работу. Больше — не лучше: каждая маска это
#: отдельный заход в Вордстат руками, и список из сорока масок не собирает
#: никто. Шесть тем закрывают почти любую услугу малого бизнеса.
MAX_TERMS = 6

#: Сколько минус-слов ставить в маску. Вордстат принимает и больше, но строку
#: перестаёт быть видно целиком, а проверить её глазами уже нельзя.
MAX_MINUS = 6

#: Коммерческие уточнения. Проверены не на красоту, а на то, что по ним
#: действительно приходят с деньгами.
_COMMERCIAL = ("купить", "цена", "заказать")

_SPLIT_RE = re.compile(r"[,;\n]+")


@dataclass(frozen=True, slots=True)
class Brief:
    """Короткий бриф. Четыре вопроса, на которые клиент отвечает за минуту."""

    #: Что продаём: «пластиковые окна, остекление балконов».
    sells: str = ""
    #: Как это называют иначе: «окна пвх, стеклопакеты». Чужие слова важнее
    #: своих: человек ищет теми, к которым привык, а не теми, что в прайсе.
    synonyms: str = ""
    #: Чего не делаем: «ремонт окон, москитные сетки». Отсюда берутся минусы —
    #: и это единственная часть брифа, которую нельзя угадать за клиента.
    excludes: str = ""
    #: Где работаем, если города не совпадают с регионом проекта.
    cities: str = ""

    @property
    def is_filled(self) -> bool:
        """Есть ли из чего строить маски. Одного «что продаём» достаточно."""
        return bool(_items(self.sells))


@dataclass(frozen=True, slots=True)
class Mask:
    """Строка, которую человек вставит в Вордстат."""

    query: str
    #: Зачем она нужна. Без этого список масок выглядит набором похожих строк,
    #: и половину из них пропускают как повтор.
    purpose: str


def _items(raw: str) -> tuple[str, ...]:
    """Разбирает поле брифа: запятые, точки с запятой и переводы строк."""
    seen: list[str] = []
    for part in _SPLIT_RE.split(raw or ""):
        item = " ".join(part.split()).strip(' "«».').lower()
        if item and item not in seen:
            seen.append(item)
    return tuple(seen)


def terms(brief: Brief) -> tuple[str, ...]:
    """Темы для сбора: что продаём плюс синонимы, без повторов.

    Повторы убираются и между полями: одно и то же слово в «что продаём» и в
    «как называют иначе» — обычное дело, а две одинаковые маски в списке
    выглядят как ошибка системы.
    """
    unique: list[str] = []
    for item in _items(brief.sells) + _items(brief.synonyms):
        if item not in unique:
            unique.append(item)
    return tuple(unique[:MAX_TERMS])


def minus_words(brief: Brief, *, niche_words: tuple[str, ...] = ()) -> tuple[str, ...]:
    """Минус-слова для маски.

    Берутся только однословные. Многословный минус в Вордстате нужно брать в
    кавычки, и строка, которую человек вставляет вручную, превращается в ребус —
    а ошибка в ней тихо испортит весь сбор. Многословное лучше отсеять потом,
    при разборе списка, где это ничего не стоит.

    Слова самой темы в минусы не попадают, и это не мелочь. «Не делаем ремонт
    окон» распадается на «ремонт» и «окон»; Вордстат минусует по всем формам
    слова, поэтому «-окон» вычеркнул бы и «окна» — то есть всю маску целиком.
    Человек получил бы пустой список и решил, что спроса нет.
    """
    candidates = [
        word
        for source in (_items(brief.excludes), niche_words)
        for item in source
        for word in tokenize(item)
        if len(word) > 2
    ]
    own = [word for term in terms(brief) for word in tokenize(term)]

    # Беглая гласная сводится по обоим спискам сразу: «окна» даёт основу «окн»,
    # «окон» — «окон», и без свода они выглядят разными словами. Ровно на этом
    # различии и построена ошибка, от которой защищаемся.
    folding = fold_beglye([stem(word) for word in candidates + own])

    def folded(word: str) -> str:
        base = stem(word)
        return folding.get(base, base)

    protected = {folded(word) for word in own}
    words: list[str] = []

    for word in candidates:
        if word not in words and folded(word) not in protected:
            words.append(word)

    return tuple(words[:MAX_MINUS])


def masks(
    brief: Brief, *, niche_words: tuple[str, ...] = (), region: str | None = None
) -> tuple[Mask, ...]:
    """Строит список масок из брифа.

    По одной широкой маске на каждую тему плюс несколько уточнённых по главной.
    Широкие идут первыми намеренно: они собирают тот самый хвост, ради которого
    в Вордстат и ходят, а коммерческие уточнения человек и так угадает сам.
    """
    found = terms(brief)
    if not found:
        return ()

    tail = " ".join(f"-{word}" for word in minus_words(brief, niche_words=niche_words))
    suffix = f" {tail}" if tail else ""

    result = [
        Mask(
            query=f"{term}{suffix}",
            purpose="Широкая маска: соберёт всё, что ищут вокруг темы, вместе с хвостом",
        )
        for term in found
    ]

    main = found[0]
    result += [
        Mask(
            query=f"{word} {main}{suffix}" if word == "купить" else f"{main} {word}{suffix}",
            purpose="Готовы платить: такие фразы дают заявки чаще прочих",
        )
        for word in _COMMERCIAL
    ]

    city = _items(brief.cities)[:1] or _items(region or "")[:1]
    if city:
        result.append(
            Mask(
                query=f"{main} {city[0]}",
                purpose=(
                    "Ищут с городом. Отдельная маска нужна потому, что регион в "
                    "Вордстате и город внутри запроса — разные вещи"
                ),
            )
        )

    return tuple(result)


