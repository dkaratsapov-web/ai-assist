"""Разметка ссылок для Метрики и CRM.

Без разметки объявление ведёт на «сайт вообще». Заявка приходит, но откуда —
из какой кампании, какой группы, по какой фразе — не знает никто. Через месяц
разговор с клиентом сводится к «реклама вроде работает», и решение о том, что
отключить, а что усилить, принимается вслепую.

Разметка это чинит одной строкой в адресе. Работа механическая: ровно поэтому
её и надо снять с человека — руками её проставляют неровно, а неровная разметка
хуже никакой. Отчёт по «yandex» и по «Yandex» — это два разных отчёта, и в
каждом половина данных.

Подстановки Директа вместо готовых значений — не украшательство. Директ
подставит в них номер кампании, номер группы и фразу, по которой был показ, уже
на своей стороне; выгружать это в файл значило бы зафиксировать номера, которых
на момент выгрузки ещё нет.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

#: Подстановки Директа. Заменяются площадкой в момент клика.
#:
#: `{campaign_id}` — номер кампании, `{gbid}` — номер группы,
#: `{keyword}` — фраза, по которой показалось объявление,
#: `{source_type}` — где показалось: поиск или сеть,
#: `{device_type}` — с чего смотрели.
CAMPAIGN_ID = "{campaign_id}"
GROUP_ID = "{gbid}"
KEYWORD = "{keyword}"
SOURCE_TYPE = "{source_type}"
DEVICE_TYPE = "{device_type}"


@dataclass(frozen=True, slots=True)
class UtmTemplate:
    """Набор меток, который подставляется во все ссылки кампании."""

    source: str = "yandex"
    medium: str = "cpc"
    #: Название кампании в отчётах. Пусто — подставится номер кампании из
    #: Директа: имя, введённое руками, рано или поздно разойдётся с настоящим.
    campaign: str = ""
    content: str = GROUP_ID
    term: str = KEYWORD

    def values(self, *, campaign_name: str = "") -> dict[str, str]:
        return {
            "utm_source": self.source,
            "utm_medium": self.medium,
            "utm_campaign": self.campaign or campaign_name or CAMPAIGN_ID,
            "utm_content": self.content,
            "utm_term": self.term,
        }


#: Метки, которые ставит сам Директ, если включена автопометка. Наши значения
#: их не трогают: две разметки в одном адресе — это спор, в котором проигрывает
#: отчёт.
YANDEX_AUTO_TAG = "yclid"

_UNSAFE = re.compile(r"[^a-z0-9_-]+")


def slug(value: str) -> str:
    """Приводит название к виду, пригодному для метки.

    Русские буквы в utm-метке живут, но в отчётах превращаются в проценты с
    цифрами, и читать их приходится в конвертере. Поэтому кириллица
    транслитерируется, а не выбрасывается: название кампании должно остаться
    узнаваемым.
    """
    lowered = value.strip().lower()
    transliterated = "".join(_TRANSLIT.get(char, char) for char in lowered)
    cleaned = _UNSAFE.sub("_", transliterated).strip("_")
    return cleaned[:60]


_TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "",
    "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def tag(url: str, template: UtmTemplate, *, campaign_name: str = "") -> str:
    """Добавляет разметку к адресу.

    Существующие параметры сохраняются: на посадочных часто уже висит что-то
    своё — идентификатор варианта страницы, метка партнёра, — и потерять его
    значит сломать чужой учёт.

    Уже проставленные utm-метки не переписываются. Если человек задал их
    вручную, у него была причина, и наша подстановка её отменила бы молча.
    """
    if not url:
        return url

    parts = urlsplit(url)
    existing = parse_qsl(parts.query, keep_blank_values=True)
    present = {key for key, _ in existing}

    added = [
        (key, value)
        for key, value in template.values(campaign_name=campaign_name).items()
        if key not in present and value
    ]

    # Подстановки Директа записываются как есть: закодированные фигурные скобки
    # площадка не распознает, и в отчёт уедет буквальное «%7Bkeyword%7D».
    query = urlencode(existing + added, safe="{}")

    return urlunsplit((parts.scheme, parts.netloc, parts.path, query, parts.fragment))


def preview(url: str, template: UtmTemplate, *, campaign_name: str = "") -> str:
    """Как ссылка будет выглядеть в отчёте, с подставленными значениями.

    Нужен на экране: строка с фигурными скобками выглядит как ошибка, и человек
    первым делом спрашивает, что это. Показать рядом пример с настоящими
    значениями дешевле, чем объяснять.
    """
    tagged = tag(url, template, campaign_name=campaign_name)
    return (
        tagged.replace(CAMPAIGN_ID, "12345678")
        .replace(GROUP_ID, "87654321")
        .replace(KEYWORD, "kupit-plastikovye-okna")
        .replace(SOURCE_TYPE, "search")
        .replace(DEVICE_TYPE, "desktop")
    )


