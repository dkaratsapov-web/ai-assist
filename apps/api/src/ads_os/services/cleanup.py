def _declensions(name: str) -> tuple[str, ...]:
    """Падежные формы названия по его окончанию.

    Правила намеренно грубые: лишняя несуществующая форма никому не мешает —
    её просто не встретится в запросах, — а пропущенная настоящая означает, что
    фраза с чужим городом уйдёт в кампанию.
    """
    word = name.lower().replace("ё", "е")

    if word.endswith(("ый", "ий", "ой")):
        base = word[:-2]
        return tuple(base + end for end in ("ый", "ого", "ом", "ому"))
    if word.endswith("а"):
        base = word[:-1]
        return tuple(base + end for end in ("а", "ы", "е", "у", "ой"))
    if word.endswith("я"):
        base = word[:-1]
        return tuple(base + end for end in ("я", "и", "е", "ю", "ей"))
    if word.endswith("ь"):
        base = word[:-1]
        return tuple(base + end for end in ("ь", "и", "е", "я", "ю", "ем", "ью"))
    # Несклоняемые в обиходе: Иваново, Сочи, Алматы, Баку.
    if word.endswith(("о", "е", "и", "ы", "у", "ю")):
        return (word,)
    return tuple(word + end for end in ("", "а", "е", "у", "ом"))


def _form_index() -> dict[str, str]:
    index: dict[str, str] = {}
    for name, extra in _CITY_TABLE:
        for form in (*_declensions(name), *extra):
            # Первый занявший форму город её и оставляет: таблица идёт от
            # крупных к мелким, и при совпадении вероятнее крупный.
            index.setdefault(form, name)
    return index


_FORM_TO_CITY = _form_index()

#: Все названия городов — по ним определяется, что причина находки в географии.
CITY_NAMES: frozenset[str] = frozenset(
    [name for name, _ in _CITY_TABLE] + list(_CITY_PHRASES.values())
)

#: Регион, при котором чужих городов не бывает.
_NATIONWIDE = ("росси", "рф", "снг", "по всей стране", "вся страна", "весь мир")

_NON_WORD_RE = re.compile(r"[^а-яa-z0-9]+", re.IGNORECASE)


def _normalized(text: str) -> str:
    return " ".join(_NON_WORD_RE.sub(" ", text.lower().replace("ё", "е")).split())


def cities_in(text: str) -> tuple[str, ...]:
    """Города, упомянутые в тексте. Порядок — как в тексте."""
    lowered = _normalized(text)
    found: list[str] = []

    for phrase, name in _CITY_PHRASES.items():
        if phrase in lowered:
            if name not in found:
                found.append(name)
            # Составное название вырезается, иначе «Нижний Новгород» дал бы ещё
            # и Новгород — и фраза оказалась бы про два города сразу.
            lowered = lowered.replace(phrase, " ")

    for token in tokenize(lowered):
        single = _FORM_TO_CITY.get(token)
        if single and single not in found:
            found.append(single)

    return tuple(found)


@lru_cache(maxsize=512)
def native_cities(region: str | None) -> frozenset[str]:
    """Города, которые для этого региона свои."""
    if not region:
        return frozenset()
    return frozenset(cities_in(region))


def is_nationwide(region: str | None) -> bool:
    """Работает ли проект по всей стране."""
    if not region:
        return False
    lowered = _normalized(region)
    return any(marker in lowered for marker in _NATIONWIDE)


def foreign_city(phrase: str, region: str | None) -> str | None:
    """Чужой город во фразе — или None, если его нет либо судить не по чему.

    Молчание здесь важнее находки. Регион может быть не заполнен, записан своими
    словами или означать всю страну — и в каждом из этих случаев объявить фразу
    нецелевой значило бы выбросить трафик по собственной догадке.
    """
    if region is None or is_nationwide(region):
        return None

    native = native_cities(region)
    if not native:
        return None

    for name in cities_in(phrase):
        if name not in native:
            return name

    return None


def reason_for(trigger: str | None, *, minus_words: frozenset[str] = frozenset()) -> Reason | None:
    """Причина, по которой сработала эта пометка."""
    if not trigger:
        return None
    if trigger in CITY_NAMES:
        return Reason.GEO
    if trigger in minus_words:
        return Reason.MINUS_WORD
    return _REASON_BY_MARKER.get(trigger)


def reason_label(reason: Reason | None) -> str | None:
    return REASON_LABELS[reason] if reason else None
