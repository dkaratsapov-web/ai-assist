_BY_KEY: dict[str, Niche] = {n.key: n for n in NICHES}


def get(key: str | None) -> Niche | None:
    """Шаблон по ключу. Неизвестный ключ — не ошибка, а отсутствие шаблона."""
    if key is None:
        return None
    return _BY_KEY.get(key)


def minus_words(niche: Niche | None) -> tuple[str, ...]:
    """Стартовый набор минус-слов: общие плюс нишевые, без повторов."""
    seen: dict[str, None] = {}
    for word in COMMON_MINUS_WORDS + (niche.minus_words if niche else ()):
        seen.setdefault(word, None)
    return tuple(seen)


def requirement_issues(niche: Niche | None, html: str) -> tuple[Issue, ...]:
    """Чего не хватает на странице по требованиям площадки для этой ниши.

    Ищем по тексту страницы целиком, а не по отдельным блокам: оговорки и
    реквизиты чаще всего лежат в подвале, который в разборе не выделяется.
    """
    if niche is None or not niche.requirements:
        return ()

    lowered = html.lower()
    found: list[Issue] = []

    for requirement in niche.requirements:
        if any(word in lowered for word in requirement.words):
            continue
        found.append(
            Issue(
                requirement.issue_key,
                Category.TRUST,
                requirement.severity,
                requirement.title,
                requirement.hint,
            )
        )

    return tuple(found)
