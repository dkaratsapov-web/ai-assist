    """Что должно быть на посадочной, иначе Директ отклонит объявления.

    `words` — по чему признак опознаётся в тексте страницы. Список намеренно
    широкий: формулировок у одного и того же требования много, а пропущенное
    требование стоит суток простоя на модерации.
    """

    issue_key: IssueKey
