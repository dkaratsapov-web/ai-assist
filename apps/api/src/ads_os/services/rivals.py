"""Кого добавить в конкуренты.

Экран конкурентов начинается с пустого поля и вопроса «а кто, собственно?».
Специалист идёт в поиск, вводит запрос, открывает четыре вкладки, копирует
адреса — и так на каждом проекте. Работа механическая, а значит, её часть можно
снять.

Снять можно ровно две части, и обе честные.

Первая: мы уже разбирали чужие сайты в других проектах. Если там та же ниша и
тот же город — это те же самые компании, с которыми клиент делит аукцион.
Предложить их дешевле, чем искать заново, и точнее: они уже проверены.

Вторая: готовые запросы для поиска. Кто именно крутит рекламу прямо сейчас,
видно только в выдаче, и увидеть это может лишь человек — поисковая выдача
роботам не отдаётся, а её разбор запрещён правилами. Зато запрос, который надо
ввести, выводится из ниши и города без всяких догадок.

Чего здесь нет: настоящих соперников по аукциону с долей пересечения. Это
знает Директ, и появится оно вместе с доступом к его API — не раньше. Рисовать
такой список из головы значило бы выдать выдумку за данные площадки.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from urllib.parse import quote_plus

#: Сколько подсказок показываем. Больше — уже не подсказка, а второй список
#: конкурентов, который надо разбирать наравне с первым.
MAX_SUGGESTIONS = 8

#: Сколько поисковых запросов даём. По каждому человек открывает выдачу и
#: смотрит рекламные места — четырёх заходов достаточно, чтобы собрать всех.
MAX_QUERIES = 4


class Source(StrEnum):
    """Откуда взялась подсказка. Без этого её нельзя оценить."""

    #: Сайт уже разбирался в другом проекте той же ниши и города.
    HISTORY = "history"
    #: Сайт другого клиента агентства в той же нише и городе.
    OWN_PROJECT = "own_project"


@dataclass(frozen=True, slots=True)
class KnownSite:
    """Сайт, о котором мы уже что-то знаем."""

    url: str
    title: str
    #: Проект, в котором он встречался. Нужен для объяснения подсказки.
    project_name: str
    niche: str | None
    region: str | None
    #: Это сайт клиента агентства, а не разобранный конкурент.
    is_own_project: bool = False


@dataclass(frozen=True, slots=True)
class Suggestion:
    url: str
    title: str
    source: Source
    #: Почему предлагается именно он. Подсказка без объяснения — это адрес
    #: неизвестно чей, и добавлять его человек не станет.
    reason: str


@dataclass(frozen=True, slots=True)
class SearchQuery:
    """Запрос, который человек вводит в поиске, чтобы увидеть рекламодателей."""

    query: str
    url: str


def suggest(
    known: tuple[KnownSite, ...],
    *,
    niche: str | None,
    region: str | None,
    exclude: frozenset[str],
) -> tuple[Suggestion, ...]:
    """Подбирает конкурентов из того, что уже разбиралось.

    Совпадение по нише обязательно: без него подсказка вырождается в список
    всех сайтов агентства. Город учитывается, когда известен у обеих сторон, —
    компании из разных городов не делят аукцион и конкурентами не являются.
    """
    if not niche:
        return ()

    result: list[Suggestion] = []
    seen: set[str] = set()

    for site in known:
        key = domain(site.url)
        if site.niche != niche or key in exclude or key in seen:
            continue
        if not _same_place(site.region, region):
            continue

        seen.add(key)
        result.append(
            Suggestion(
                url=site.url,
                title=site.title or site.url,
                source=Source.OWN_PROJECT if site.is_own_project else Source.HISTORY,
                reason=(
                    f"Сайт вашего проекта «{site.project_name}» — та же ниша и тот же город. "
                    "За клики в одном аукционе они конкурируют между собой."
                    if site.is_own_project
                    else f"Вы разбирали его в проекте «{site.project_name}»: та же ниша и город."
                ),
            )
        )
        if len(result) == MAX_SUGGESTIONS:
            break

    return tuple(result)


def _same_place(theirs: str | None, ours: str | None) -> bool:
    """Один ли это рынок.

    Когда регион не заполнен хотя бы у одной стороны, сравнивать нечего, и
    подсказка остаётся: пусть человек решает сам. Отбросить её значило бы
    промолчать там, где мы просто не знаем.
    """
    if not theirs or not ours:
        return True
    return theirs.strip().lower() == ours.strip().lower()


def domain(url: str) -> str:
    """Домен без схемы, www и хвоста. По нему и сверяем повторы."""
    cleaned = url.split("://")[-1].split("/")[0].lower()
    return cleaned.removeprefix("www.")


def search_queries(terms: tuple[str, ...], region: str | None) -> tuple[SearchQuery, ...]:
    """Готовые запросы, по которым видно, кто крутит рекламу.

    Город добавляется в сам запрос: местная услуга и та же услуга по стране —
    это две разные выдачи с разными рекламодателями.
    """
    city = (region or "").strip()
    result: list[SearchQuery] = []

    for term in terms:
        for text in (f"{term} {city}".strip(), f"купить {term} {city}".strip()):
            if text in {item.query for item in result}:
                continue
            result.append(
                SearchQuery(query=text, url=f"https://yandex.ru/search/?text={quote_plus(text)}")
            )
            if len(result) == MAX_QUERIES:
                return tuple(result)

    return tuple(result)


