"""Запуск асинхронного кода внутри задачи Celery.

Задачи Celery синхронные, а вся работа с базой — асинхронная, поэтому каждая
задача поднимает свой цикл событий через asyncio.run.

Отсюда и проблема, ради которой существует этот модуль. Движок SQLAlchemy
кэшируется на уровне процесса, а его пул держит соединения, привязанные к тому
циклу, в котором они открывались. Цикл закрывается вместе с asyncio.run, но
соединения остаются в пуле — и следующая задача в том же процессе получает
соединение от закрытого цикла и падает с «attached to a different loop».

Проявлялось это не сразу: первая задача в процессе всегда проходила успешно.
Ломалась вторая — то есть на живом стенде отказ выглядел бы как случайный.

Поэтому пул закрывается в конце каждой задачи, внутри её же цикла. Плата —
новые соединения на каждую задачу; для фоновых операций, которые длятся
секунды, это несопоставимо дешевле, чем плавающий отказ.
"""

from __future__ import annotations

import asyncio
from collections.abc import Awaitable, Callable
from typing import TypeVar

from ..db.session import dispose_engine

T = TypeVar("T")


def run_task(operation: Callable[[], Awaitable[T]]) -> T:
    """Выполняет асинхронную операцию задачи и закрывает пул соединений."""

    async def runner() -> T:
        try:
            return await operation()
        finally:
            await dispose_engine()

    return asyncio.run(runner())
