"""Приведение почты к одному виду.

Доступ выдаётся по почте, а вход идёт через Яндекс. Между этими двумя
событиями почта успевает поменять вид, и человек, которому доступ выдали,
получает отказ.

Как именно это происходит.

**Домены-синонимы.** `ivan@ya.ru`, `ivan@yandex.ru`, `ivan@yandex.com`,
`ivan@yandex.by` — один и тот же ящик одного и того же человека. Владелец
записывает тот адрес, который знает, а Яндекс при входе возвращает
`yandex.ru` — и сравнение строк не совпадает.

**Точка и дефис в логине.** У Яндекса `ivan.petrov` и `ivan-petrov` — один
логин. Владелец пишет с точкой, потому что так в визитке; Яндекс присылает с
дефисом.

Поэтому сравниваются не строки, а приведённая форма. Хранится при этом
исходная: человек должен видеть в списке участников тот адрес, который сам
вписал, а не результат наших преобразований.

Чужие домены не трогаются вовсе, кроме регистра и пробелов. Правила Яндекса
верны для Яндекса — переносить их на gmail или на корпоративный ящик значило
бы считать два разных ящика одним.
"""

from __future__ import annotations

#: Домены, ведущие в один и тот же ящик Яндекса.
YANDEX_DOMAINS = frozenset(
    {
        "yandex.ru",
        "yandex.com",
        "yandex.by",
        "yandex.kz",
        "yandex.ua",
        "yandex.com.tr",
        "ya.ru",
    }
)

CANONICAL_DOMAIN = "yandex.ru"


def normalize(email: str) -> str:
    """Приводит почту к виду, по которому её и сравнивают.

    Результат не показывается человеку и не заменяет собой введённый адрес: он
    нужен только для сопоставления.
    """
    cleaned = email.strip().lower()
    local, _, domain = cleaned.partition("@")

    if not local or not domain:
        return cleaned

    if domain not in YANDEX_DOMAINS:
        return f"{local}@{domain}"

    # Точка и дефис в логине Яндекса равнозначны. Приводим к одному символу,
    # а не удаляем: два разных логина «ivanpetrov» и «ivan.petrov» — это
    # действительно разные люди, и склеивать их нельзя.
    return f"{local.replace('.', '-')}@{CANONICAL_DOMAIN}"


def same_person(left: str, right: str) -> bool:
    """Один ли это ящик."""
    return normalize(left) == normalize(right)


def looks_like_email(value: str) -> bool:
    """Похоже ли это вообще на почту.

    Проверка нарочно грубая. Строгая проверка адреса по стандарту отвергает
    существующие рабочие ящики, а настоящую пригодность адреса всё равно
    покажет только вход: доступ по почте, на которую никто не войдёт, никому
    не вредит.
    """
    cleaned = value.strip()
    local, _, domain = cleaned.partition("@")
    return bool(local) and "." in domain and " " not in cleaned and len(cleaned) <= 320
