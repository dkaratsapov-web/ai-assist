#: Многословные признаки: по одному слову их не поймать, а поймать надо —
#: «своими руками» встречается в выгрузке чаще любого одиночного слова.
PHRASE_GROUPS: dict[Reason, tuple[str, ...]] = {
    Reason.DIY: ("своими руками", "сделать самому", "своими силами", "мастер класс"),
    Reason.JOB: ("ищу работу", "работа вахтой"),
    Reason.FREE: ("бесплатно скачать", "скачать бесплатно"),
    # «б у» отдельными буквами не ищется: эти два символа встречаются внутри
    # обычных фраз («клуб уюта»), и находка была бы ложной.
    Reason.USED: ("бывшие в употреблении",),
    Reason.STUDY: ("курсовая работа", "дипломная работа"),
    Reason.FRAUD: ("черный список", "кинули на деньги"),
}


def _reason_index() -> dict[str, Reason]:
    index: dict[str, Reason] = {}
    for reason, words in MARKER_GROUPS.items():
        for word in words:
            index[word] = reason
    for reason, phrases in PHRASE_GROUPS.items():
        for phrase in phrases:
            index[phrase] = reason
    return index


_REASON_BY_MARKER = _reason_index()

#: Все однословные признаки одним множеством — для разбора фраз.
MARKERS: frozenset[str] = frozenset(_REASON_BY_MARKER) - {
    phrase for phrases in PHRASE_GROUPS.values() for phrase in phrases
}

#: Все многословные признаки. Порядок важен: длинные проверяются первыми, иначе
#: «скачать бесплатно» объяснится словом «бесплатно» вместо целой фразы.
PHRASES: tuple[str, ...] = tuple(
    sorted(
        (phrase for phrases in PHRASE_GROUPS.values() for phrase in phrases),
        key=lambda item: -len(item),
    )
)


