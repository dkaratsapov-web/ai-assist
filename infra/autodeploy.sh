#!/usr/bin/env bash
#
# Самообновление сервера.
#
# Запускается по расписанию, смотрит, появились ли новые изменения в ветке, и
# если появились — забирает их и пересобирает. Человек в этом не участвует.
#
# Почему это вообще существует. Разработка идёт в среде, из которой наружу
# открыт только HTTPS: порт SSH закрыт, и выложить обновление на сервер оттуда
# нельзя физически. Оставался единственный способ — просить владельца каждый
# раз вводить одни и те же три команды. Это работа, которую машина делает
# лучше человека: она не забудет, не опечатается и не пропустит обновление,
# потому что была занята.
#
# Что здесь важно и неочевидно:
#
# * Состояние хранится отдельным файлом, а не выводится из HEAD. Если сборка
#   упала, HEAD уже сдвинут, и сравнение с ним показало бы «всё свежее» —
#   поломка застыла бы до следующего изменения в ветке. С файлом упавшая
#   сборка повторяется на каждом запуске, пока не соберётся.
#
# * Слияние только перемоткой. Если на сервере оказались свои изменения,
#   обновление честно остановится, а не затрёт их молча.
#
# * Замок от наложения запусков. Сборка идёт минутами, расписание — чаще;
#   без замка два процесса собирали бы одно и то же одновременно.
#
# * Упавшая сборка не роняет работающий сайт: docker compose поднимает новые
#   контейнеры только после успешной сборки, старые продолжают отвечать.

set -euo pipefail

REPO="${ADS_OS_REPO:-/root/ai-assist}"
COMPOSE="$REPO/infra/docker-compose.yml"
STATE="$REPO/.last-deployed"
LOCK="/var/lock/ads-os-deploy.lock"

log() {
    printf '%s %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"
}

exec 9>"$LOCK"
if ! flock -n 9; then
    log "предыдущее обновление ещё идёт — пропускаем"
    exit 0
fi

cd "$REPO"

branch="$(git rev-parse --abbrev-ref HEAD)"

if ! git fetch --quiet origin "$branch"; then
    log "не удалось связаться с GitHub — попробуем в следующий раз"
    exit 0
fi

remote="$(git rev-parse "origin/$branch")"
deployed="$(cat "$STATE" 2>/dev/null || echo "")"

if [ "$remote" = "$deployed" ]; then
    exit 0
fi

log "новое изменение в ветке $branch: ${remote:0:8}"

if ! git merge --ff-only "origin/$branch"; then
    # Перемотка не прошла — значит, на сервере правили файлы руками. Молча
    # затирать чужую работу нельзя, поэтому останавливаемся и говорим об этом.
    log "ОШИБКА: на сервере есть свои изменения, обновление остановлено"
    log "разберите их вручную: git status"
    exit 1
fi

log "сборка и перезапуск"

if docker compose -f "$COMPOSE" up -d --build; then
    echo "$remote" > "$STATE"
    log "готово: ${remote:0:8}"
else
    # Состояние не записываем: следующий запуск попробует снова. Сайт при этом
    # продолжает работать на прежних контейнерах.
    log "ОШИБКА: сборка не удалась, сайт остался на прежней версии"
    exit 1
fi

# Мусор от старых сборок иначе съедает диск за пару недель ежедневных
# обновлений — а место на этом сервере считаное.
docker image prune -f >/dev/null 2>&1 || true
