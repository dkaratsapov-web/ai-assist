#!/bin/sh
# Снимает копию сразу при старте, дальше — раз в сутки.
#
# Копия при старте нужна не для расписания, а чтобы неработающие копии
# обнаруживались сразу после развёртывания, а не через сутки. Молчаливо
# сломанный бэкап хуже отсутствующего: на него рассчитывают.
set -eu

/usr/local/bin/backup.sh || echo "первая копия не удалась" >&2

while true; do
  sleep 86400
  /usr/local/bin/backup.sh || echo "плановая копия не удалась" >&2
done
