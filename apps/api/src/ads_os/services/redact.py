"""Вычистка контактов из текста перед отправкой модели.

Модели отдаётся текст чужой страницы — и вместе с ним туда уехали бы телефоны
и почтовые адреса, которые на этой странице напечатаны. Для разбора они не
нужны ни разу: чтобы оценить предложение и работу с возражениями, номер
телефона не требуется. А раз не нужны — не отправляются.

Это не заменяет запрет на отправку персональных данных: он живёт выше, в слое
провайдера, и отсекает целые режимы работы. Здесь — вторая линия, для текста,
который сам по себе публичный, но содержит контакты.

Чего эта вычистка не делает. Имён и фамилий она не ищет: отличить фамилию от
названия компании или марки в русском тексте без словаря невозможно, а
подставлять сюда ненадёжное угадывание — значит портить текст в случайных
местах и при этом ничего не гарантировать. Имена на странице «Наша команда»
остаются: это опубликованные самой компанией данные, и граница проведена
именно здесь — осознанно, а не по недосмотру.
"""

from __future__ import annotations

import re

PHONE_MARK = "[телефон]"
EMAIL_MARK = "[почта]"

#: Телефон в привычном виде: одиннадцать цифр с любыми разделителями либо
#: десять без кода страны. Шаблон намеренно узкий — цену «от 1 200 000 ₽»
#: он не трогает.
_PHONE = re.compile(
    r"(?<![\d\-])(?:\+?7|8)?[\s\-–(]*\d{3}[\s\-–)]*\d{3}[\s\-–]*\d{2}[\s\-–]*\d{2}(?![\d\-])"
)

_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")

#: Ссылки, ведущие прямо на человека.
_CONTACT_LINK = re.compile(r"\b(?:tel|mailto|callto):\S+", re.IGNORECASE)


def redact(text: str) -> str:
    """Заменяет контакты пометками, сохраняя остальной текст как есть.

    Пометка, а не пустое место: модель должна видеть, что телефон на странице
    был. «Позвоните нам [телефон]» и «Позвоните нам» — разные страницы, и
    вторая заслуживает замечания, которого первая не заслуживает.
    """
    text = _CONTACT_LINK.sub(PHONE_MARK, text)
    text = _EMAIL.sub(EMAIL_MARK, text)
    return _PHONE.sub(PHONE_MARK, text)


def has_contacts(text: str) -> bool:
    """Есть ли в тексте контакты. Нужна тестам и проверкам, не логике."""
    return bool(_PHONE.search(text) or _EMAIL.search(text) or _CONTACT_LINK.search(text))
