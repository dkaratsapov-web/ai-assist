"""Шаблоны ниш: с чего не начинать каждый проект заново.

Специалист, который десятый раз ведёт пластиковые окна, уже знает наизусть:
отминусовать «своими руками», проверить, что на сайте есть политика обработки
данных, и не обещать в объявлении «самые лучшие». Этот модуль хранит такое
знание в коде, чтобы оно не зависело от того, вспомнил человек про него сегодня
или нет.

Чего здесь намеренно нет — цифр экономики. Соблазн записать в шаблон
«конверсия сайта в этой нише 2,5 %» велик, но такое число невозможно ни
проверить, ни защитить перед клиентом: оно зависит от региона, сезона, цены и
самого сайта сильнее, чем от отрасли. Правдоподобная цифра на месте незнания —
ровно та ошибка, от которой весь расчёт экономики защищается тремя состояниями
достоверности (v0.4 §5). Поэтому шаблон ниши даёт только то, что проверяемо:
слова, требования площадки и вопросы, которые в этой нише стоит задать.

Требования модерации — не наша выдумка и не осторожность: это правила Яндекс
Директа для рекламы медицины, БАДов, юридических и финансовых услуг. Объявление
без них отклоняется, и узнать об этом лучше до запуска, чем на модерации.
"""

